import fs from "node:fs";
import assert from "node:assert/strict";

const read = path => fs.readFileSync(path, "utf8");
const pkg = JSON.parse(read("package.json"));
const version = JSON.parse(read("VERSION.json"));
const app = read("public/app/app.js");
const index = read("index.html");
const css = read("public/app/styles.css");

assert.equal(pkg.version, "1.2.6");
assert.equal(version.semver, "1.2.6");
assert.ok(index.includes('id="researchMinimapInfo"'), "missing minimap hover information panel");
assert.ok(app.includes("v122DrawMinimapObjects"), "minimap does not draw object distribution");
assert.ok(app.includes("v122DrawMinimapWaterways"), "minimap does not draw waterways");
assert.ok(app.includes("V122_MINIMAP_LAYERS"), "minimap does not expose L1-L4 world layers");
assert.ok(app.includes("minimap._minimapPoints"), "minimap object hit-test index is missing");
assert.ok(app.includes("minimap.classList.contains('is-expanded')?9:7"), "responsive minimap hover hit test is missing");
assert.ok(css.includes(".research-minimap-info"), "minimap information panel styling is missing");
assert.ok(index.includes('id="minimapExpandBtn"'), "compact / expanded minimap control is missing");
assert.ok(css.includes(".research-minimap.is-expanded"), "expanded minimap styling is missing");
assert.ok(app.includes("clusters=new Map()"), "minimap should cluster dense object markers");
assert.ok(app.includes("expanded&&state.overviewMode!=='region'"), "default region minimap must not draw every audit boundary");
assert.ok(!app.includes("for(const label of (BOARD_LAYOUT.worldLabels||[]).slice(0,32))"), "old long world-label renderer still obscures the overview");
assert.ok(app.includes("v122UseWorldRegionAtlas"), "direct world-region atlas mode is missing");
assert.ok(app.includes("v122AtlasRegionName") && app.includes("v122AtlasRegionGroups"), "V282 objects are not synthesized into readable atlas regions");
assert.ok(app.includes("(state.camera.zoom||1)<.50"), "region atlas should remain visible from 18% until object-detail zoom");
assert.ok(app.includes("if(!v272BoardLayoutAvailable()||v122UseWorldRegionAtlas())return"), "engineering world labels still obscure the region atlas");
assert.ok(app.includes("if(group.atlasRegion)"), "atlas regions do not zoom into their contained locations");
assert.ok(app.includes('worldGroup=v122UseWorldRegionAtlas()&&!group.macroRegion'), "world overview does not render real region groups directly on the map");
assert.ok(css.includes(".region-overview-label.world-region-group"), "compact world region group styling is missing");
assert.ok(!app.includes("renderV122WorldLayerNavigator"), "obsolete L1-L4 button navigator should not replace the world map");
console.log("PASS v1.2.2 useful minimap overview");
